"""
Pydantic data schemas representing the structured Ship Pack response.
"""
from __future__ import annotations
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class RiskLevel(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ShippingReadiness(str, Enum):
    READY = "ready"
    REVIEW_RECOMMENDED = "review recommended"
    NOT_READY = "not ready"


class PotentialIssue(BaseModel):
    """Specific vulnerability, flaw, or risk found in the code."""
    title: str = Field(description="Concise description of the potential bug or issue.")
    severity: str = Field(description="Severity tier: exactly 'low', 'medium', or 'high'.")
    explanation: str = Field(description="Factual explanation of how and why this issue could occur, distinguishing confirmed flaws from potential risks.")
    suggested_action: str = Field(description="Actionable mitigation, code fix, or canary check to address this issue.")

    @field_validator("severity", mode="before")
    @classmethod
    def normalize_severity(cls, v: str) -> str:
        if isinstance(v, str):
            clean = v.strip().lower()
            if clean in ["low", "medium", "high"]:
                return clean
            if "crit" in clean or "high" in clean:
                return "high"
            if "med" in clean:
                return "medium"
            return "low"
        return "medium"


class IssueDeepDive(BaseModel):
    """Interactive deep-dive explanation and recommended fix for a potential issue."""
    why_this_matters: str = Field(description="Production impact on reliability, latency, security, or data integrity.")
    where_problem_occurs: str = Field(description="Specific file, function, line reference, or code execution path.")
    recommended_approach: str = Field(description="Engineering pattern or approach to resolve the issue.")
    example_fix_code: Optional[str] = Field(default=None, description="Concrete code snippet or diff if enough context exists.")
    missing_context_needed: Optional[str] = Field(default=None, description="Specific additional information needed if context is insufficient to safely produce code.")
    has_sufficient_context: bool = Field(default=True, description="Whether the provided code had sufficient context for an exact fix.")


class TestScenario(BaseModel):
    """Concrete test scenario to verify the code change."""
    test_name: str = Field(description="Descriptive name of the test case.")
    test_description: str = Field(description="Detailed verification steps, failure paths, and expected success criteria.")
    priority: str = Field(description="Priority: exactly 'high', 'medium', or 'low'.")

    @field_validator("priority", mode="before")
    @classmethod
    def normalize_priority(cls, v: str) -> str:
        if isinstance(v, str):
            clean = v.strip().lower()
            if clean in ["high", "medium", "low"]:
                return clean
            if "p0" in clean or "p1" in clean or "high" in clean or "crit" in clean:
                return "high"
            if "p2" in clean or "med" in clean:
                return "medium"
            return "low"
        return "medium"


class ShipPackAnalysis(BaseModel):
    """Complete, strictly structured Ship Pack generated by the LLM analysis layer."""
    change_summary: str = Field(description="Factual, high-level summary of what actually changed in the code.")
    change_purpose: str = Field(description="The underlying purpose or root problem being solved.")
    change_type: str = Field(description="Type of change: e.g. bug fix, feature, refactoring, performance, security, etc.")
    
    risk_level: RiskLevel = Field(description="Overall risk level: 'low', 'medium', or 'high'.")
    risk_explanation: str = Field(description="Detailed justification of the risk level based strictly on the provided code.")
    
    potential_issues: List[PotentialIssue] = Field(
        default_factory=list,
        description="List of concrete potential issues or bugs detected in the code change."
    )
    edge_cases: List[str] = Field(
        default_factory=list,
        description="Specific edge cases or boundary conditions that should be verified."
    )
    test_scenarios: List[TestScenario] = Field(
        default_factory=list,
        description="Recommended test scenarios with name, steps/description, and priority."
    )
    
    manager_update: str = Field(description="Non-technical executive update explaining progress, business impact, and release status.")
    ticket_update: str = Field(description="Ready-to-paste markdown ticket update for Jira, Linear, or GitHub PR description.")
    technical_documentation: str = Field(description="Technical documentation explaining code behavior, interfaces, or architectural changes.")
    release_notes: str = Field(description="Clean, user-facing release notes or changelog entry.")
    
    shipping_readiness: ShippingReadiness = Field(description="Verdict: 'ready', 'review recommended', or 'not ready'.")
    readiness_reason: str = Field(description="Clear explanation supporting the shipping readiness verdict.")
    
    ship_score: int = Field(
        default=85,
        ge=0,
        le=100,
        description="Ship score from 0 to 100 summarizing apparent release readiness based on risk, error handling, edge cases, and test coverage."
    )
    score_factor_explanation: str = Field(
        default="Defensive implementation with backward compatibility and standard testing needed.",
        description="One-sentence explanation of the primary factor affecting the ship score."
    )
    analyzed_at: Optional[str] = Field(
        default=None,
        description="UTC timestamp of when the analysis was performed."
    )
    provider_used: Optional[str] = Field(default="gemini", description="Label of the provider/model that performed the analysis.")

    @field_validator("risk_level", mode="before")
    @classmethod
    def normalize_risk(cls, v: str) -> RiskLevel:
        if isinstance(v, str):
            clean = v.strip().lower()
            if clean in ["low", "medium", "high"]:
                return RiskLevel(clean)
            if "crit" in clean or "high" in clean:
                return RiskLevel.HIGH
            if "med" in clean:
                return RiskLevel.MEDIUM
            return RiskLevel.LOW
        return v

    @field_validator("shipping_readiness", mode="before")
    @classmethod
    def normalize_readiness(cls, v: str) -> ShippingReadiness:
        if isinstance(v, str):
            clean = v.strip().lower().replace("_", " ").replace("-", " ")
            if clean in ["ready", "review recommended", "not ready"]:
                return ShippingReadiness(clean)
            if "ready to ship" in clean or clean == "ready":
                return ShippingReadiness.READY
            if "not" in clean or "block" in clean:
                return ShippingReadiness.NOT_READY
            return ShippingReadiness.REVIEW_RECOMMENDED
        return v

    @model_validator(mode="after")
    def prioritize_findings(self) -> "ShipPackAnalysis":
        """Ensures highest severity issues and highest priority tests are presented first."""
        sev_rank = {"high": 0, "medium": 1, "low": 2}
        if self.potential_issues:
            self.potential_issues.sort(key=lambda x: sev_rank.get(x.severity.lower(), 1))
        
        prio_rank = {"high": 0, "medium": 1, "low": 2}
        if self.test_scenarios:
            self.test_scenarios.sort(key=lambda x: prio_rank.get(x.priority.lower(), 1))
        return self


# Backward compatibility alias
ShipPack = ShipPackAnalysis
